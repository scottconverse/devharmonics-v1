function freezeShape(shape) {
  return Object.freeze(
    Object.fromEntries(
      Object.entries(shape).map(([table, columns]) => [table, Object.freeze([...columns])]),
    ),
  );
}

function freezeManifest(source, version, requiredShape) {
  return Object.freeze({
    tag: source,
    version,
    migrationNames: Object.freeze(migrationNamesThrough37.slice(0, version)),
    requiredShape: freezeShape(requiredShape),
  });
}

